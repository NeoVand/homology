/** Representatives of [k] in ℤ/n shown by the tester: k − n, k, k + n, k + 2n. */
export function representatives(k: number, n: number): number[] {
	return [k - n, k, k + n, k + 2 * n];
}

/**
 * Check a rule on ℤ/n by sampling representatives of every class.
 * (For the rules above this sampling is decisive: each output depends only on x mod lcm(n, m),
 * and the sampled representatives already disagree whenever the rule fails.)
 */
export function checkRule(rule: Rule, n: number): { ok: boolean; badClass: number | null } {
	for (let k = 0; k < n; k++) {
		const outs = new Set(representatives(k, n).map((x) => rule.out(x, n)));
		if (outs.size > 1) return { ok: false, badClass: k };
	}
	return { ok: true, badClass: null };
}
