	<div class="grid">
		<section class="card panel">
			<h2>Chains and boundaries</h2>
			<p>An oriented \(k\)-simplex \([v_0,\dots,v_k]\). A \(k\)-chain is a formal sum of \(k\)-simplices with coefficients in \(G\):</p>
			\[ C_k(K;G) = \Big\{ \textstyle\sum_i g_i \sigma_i \Big\}. \]
			<p>The boundary operator:</p>
			\[ \begin{gathered} \partial\,[v_0,\dots,v_k] = \sum_{i=0}^{k} (-1)^i\,[v_0,\dots,\hat v_i,\dots,v_k], \\[8pt] \partial\circ\partial = 0. \end{gathered} \]
			{@render go('homology/chains')}
		</section>

		<section class="card panel">
			<h2>Homology</h2>
			<p>Cycles are chains with no boundary; boundaries are boundaries of something one dimension up:</p>
			\[ \begin{aligned} Z_k &= \ker\partial_k, \\ B_k &= \im\partial_{k+1} \subseteq Z_k, \\ H_k &= Z_k / B_k. \end{aligned} \]
			<p>Betti numbers (over a field \(\F\)), with \(n_k\) the number of \(k\)-simplices:</p>
			\[ \begin{aligned} b_k &= \dim H_k \\ &= n_k - \rank\partial_k - \rank\partial_{k+1}. \end{aligned} \]
			{@render go('homology/homology-groups')}
		</section>

		<section class="card panel">
			<h2>Euler–Poincaré</h2>
			<p>The alternating count of cells equals the alternating sum of Betti numbers:</p>
			\[ \chi(X) = \sum_k (-1)^k n_k = \sum_k (-1)^k b_k. \]
			<p>For closed surfaces: \(\chi(\Sigma_g) = 2 - 2g\) (orientable, genus \(g\)); \(\chi = 2 - k\) for a sum of \(k\) projective planes.</p>
			{@render go('homology/homology-groups', 'euler-poincare')}
		</section>

		<section class="card panel">
			<h2>Torsion</h2>
			<p>Every finitely generated abelian group is</p>
			\[ \begin{gathered} \Z^{r} \oplus \Z/d_1 \oplus \cdots \oplus \Z/d_m, \\ \text{with } d_1 \mid d_2 \mid \cdots \mid d_m . \end{gathered} \]
			<p>The free rank is read from ranks of boundary matrices; the torsion \(\Z/d_i\) of \(H_k\) from the Smith normal form of \(\partial_{k+1}\) (diagonal entries \(d_i > 1\)).</p>
			{@render go('homology/computing')}
		</section>

		<section class="card panel">
			<h2>Invariance and functoriality</h2>
			<p>A continuous map \(f\colon X\to Y\) induces \(f_*\colon H_k(X)\to H_k(Y)\), with</p>
			\[ \begin{gathered} (g\circ f)_* = g_*\circ f_*, \qquad (\id_X)_* = \id, \\ f\simeq g \;\Rightarrow\; f_* = g_*. \end{gathered} \]
			<p>So homotopy-equivalent spaces have isomorphic homology. Payoffs: Brouwer’s fixed point theorem, the hairy ball theorem, invariance of dimension.</p>
			{@render go('homology/invariance')}
		</section>

		<section class="card panel">
			<h2>Exact sequences</h2>
			<p>Mayer–Vietoris, for \(X = U\cup V\) with \(U, V\) open:</p>
			\[ \begin{aligned} \cdots &\to H_k(U\cap V) \to H_k(U)\oplus H_k(V) \\ &\to H_k(X) \xrightarrow{\;\partial_*\;} H_{k-1}(U\cap V) \to \cdots \end{aligned} \]
			<p>Every map’s image is exactly the next map’s kernel.</p>
			{@render go('homology/exact-sequences')}
		</section>

		<section class="card panel">
			<h2>Knots</h2>
			<p>For every knot \(K\), Mayer–Vietoris gives \(H_1(S^3\setminus K)\cong\Z\), generated by the meridian \(\mu\); the class of a loop is its linking number with \(K\):</p>
			\[ [\gamma] = \operatorname{lk}(\gamma, K)\,[\mu]. \]
			<p>Finer invariants: the Alexander polynomial from a Seifert matrix \(V\), the Jones polynomial from the Kauffman bracket of a diagram \(D\), and Khovanov homology, whose graded Euler characteristic is the Jones polynomial:</p>
			\[ \begin{gathered} \Delta_K(t) \doteq \det\big(V - tV^{\mathsf T}\big), \\[4pt] V_K(t) = \bigl(-A^3\bigr)^{-w(D)}\langle D\rangle, \quad A = t^{-1/4}, \\[4pt] \textstyle\sum_{i,j}(-1)^i q^j \dim \mathit{Kh}^{i,j}(K) = (q+q^{-1})\,V_K(q^2). \end{gathered} \]
			{@render go('homology/knots')}
		</section>

		<section class="card panel">
			<h2>Persistence</h2>
			<p>Grow balls of radius \(r\) around the points of a cloud \(P\). The Čech complex is their nerve and has the homology of their union \(U_r\); the Vietoris–Rips complex only asks the balls to meet in pairs:</p>
			\[ \check C_r(P) \subseteq \mathrm{VR}_r(P) \subseteq \check C_{\sqrt2\,r}(P). \]
			<p>As \(r\) grows, each class is born and dies; the intervals \([b, d)\) form the barcode. Stability: moving every point by at most \(\delta\) moves the diagrams by at most \(\delta\),</p>
			\[ d_B\big(\mathcal D_k(P), \mathcal D_k(P')\big) \le \delta. \]
			{@render go('homology/persistence')}
		</section>

		<section class="card panel">
			<h2>Cohomology</h2>
			<p>Cochains measure chains; the coboundary is the transpose of the boundary:</p>
			\[ \begin{gathered} C^k(K;G) = \Hom(C_k(K), G), \\ (\delta\varphi)(\sigma) = \varphi(\partial\sigma), \qquad \delta\circ\delta = 0, \\[2pt] H^k = \ker\delta^k \big/ \im\delta^{k-1}. \end{gathered} \]
			<p>Maps pull back: \(f\colon X\to Y\) gives \(f^*\colon H^k(Y)\to H^k(X)\).</p>
			{@render go('cohomology/cohomology-groups')}
		</section>

		<section class="card panel">
			<h2>Universal coefficients</h2>
			<p>Cohomology is determined by homology, but torsion moves up one degree:</p>
			\[ \begin{aligned} H^k(X;\Z) &\cong \Hom\big(H_k(X),\Z\big) \\ &\quad \oplus\, \Ext\big(H_{k-1}(X),\Z\big). \end{aligned} \]
			<p>Example: \({H_1(\RP^2) = \Z/2}\) and \({H_2(\RP^2) = 0}\), yet \({H^2(\RP^2;\Z) = \Z/2}\).</p>
			{@render go('cohomology/cohomology-groups', 'universal-coefficients')}
		</section>

		<section class="card panel">
			<h2>de Rham and Stokes</h2>
			\[ \begin{gathered} \int_{\partial M}\omega = \int_M d\omega, \qquad d\circ d = 0, \\[6pt] \begin{aligned} H^k_{\dR}(M) &= \frac{\{\text{closed } k\text{-forms}\}}{\{\text{exact } k\text{-forms}\}} \\[2pt] &\cong H^k(M;\R). \end{aligned} \end{gathered} \]
			<p>On the punctured plane, \(d\theta = (-y\,dx + x\,dy)/(x^2+y^2)\) is closed but not exact: \(\oint_\gamma d\theta = {2\pi\cdot(\text{winding number of }\gamma)}\).</p>
			{@render go('cohomology/de-rham')}
		</section>

		<section class="card panel">
			<h2>Cup product</h2>
			\[ \begin{aligned} (\alpha\smile\beta)(\sigma) &= \alpha\big(\sigma|_{[v_0,\dots,v_p]}\big) \\ &\quad \cdot \beta\big(\sigma|_{[v_p,\dots,v_{p+q}]}\big), \\[4pt] \alpha\smile\beta &= (-1)^{pq}\,\beta\smile\alpha. \end{aligned} \]
			<p>\(T^2\) and \(S^1\vee S^1\vee S^2\) have the same groups; on \(T^2\), \(a\smile b\) generates \(H^2\), on the wedge every such product is \(0\).</p>
			{@render go('cohomology/cup-product')}
		</section>

		<section class="card panel">
			<h2>Poincaré duality</h2>
			<p>For a closed, oriented \(n\)-manifold \(M\):</p>
			\[ \begin{gathered} H^k(M;\Z) \;\cong\; H_{n-k}(M;\Z), \\ b_k = b_{n-k}. \end{gathered} \]
			<p>With \(\Z/2\) coefficients it holds for every closed manifold, orientable or not.</p>
			{@render go('cohomology/poincare-duality')}
		</section>

		<section class="card panel">
			<h2>Sheaves and Čech cohomology</h2>
			<p>Cover \(X\) by open sets \(\mathcal U\) and do cohomology on the overlaps. For a good cover the nerve has the homotopy type of \(X\), so</p>
			\[ \check H^p(\mathcal U; G) \cong H^p(X; G). \]
			<p>For a sheaf \(F\) of local data, \(\check H^0 = F(X)\) is the global sections: local solutions that agree on overlaps. \(\check H^1\) measures how local solutions fail to glue.</p>
			{@render go('cohomology/sheaves')}
		</section>

		<section class="card panel">
			<h2>Gauss–Bonnet</h2>
			<p>Total curvature of a closed surface is topology:</p>
			\[ \int_M K\, dA = 2\pi\,\chi(M). \]
			<p>Sphere: \(4\pi\). Torus: \(0\). The hairy ball theorem: a sphere has no nowhere-zero tangent vector field, because \(\chi(S^2) = 2 \neq 0\).</p>
			{@render go('cohomology/characteristic-classes')}
		</section>

		<section class="card panel">
			<h2>Categories and functors</h2>
			<p>A functor \(F\colon\mathcal C\to\mathcal D\) sends objects to objects and arrows to arrows, keeping identities and composition; homology \(H_n\colon\Top\to\Ab\) is one. A natural transformation \(\eta\colon F\Rightarrow G\) has components \(\eta_X\colon F(X)\to G(X)\) with</p>
			\[ G(f)\circ\eta_X = \eta_Y\circ F(f) \]
			<p>for every arrow \(f\colon X\to Y\): the naturality square commutes.</p>
			{@render go('big-picture/categories')}
		</section>

		<section class="card panel">
			<h2>The axioms</h2>
			<p>Eilenberg and Steenrod: a homology theory is a functor on pairs with connecting maps \(\partial\), satisfying homotopy, exactness, excision, dimension and additivity. Given the group of a point, these five axioms determine it on finite complexes; with \(H_0(\mathrm{pt}) = \Z\),</p>
			\[ H_n(S^k) \cong \begin{cases} \Z & n = 0 \text{ or } n = k, \\ 0 & \text{otherwise} \end{cases} \quad (k \ge 1). \]
			<p>Drop the dimension axiom and you get the generalized theories, such as bordism and K-theory.</p>
			{@render go('big-picture/homological-algebra')}
		</section>

		<section class="card panel">
			<h2>Hodge decomposition</h2>
			<p>Every flow \(f\) on the edges of a complex splits, perpendicularly, into a gradient, a curl and a harmonic part:</p>
			\[ \begin{gathered} f = \delta_0 s + \delta_1^{\mathsf T}\varphi + h, \\[4pt] \|f\|^2 = \|\delta_0 s\|^2 + \|\delta_1^{\mathsf T}\varphi\|^2 + \|h\|^2. \end{gathered} \]
			<p>Each class of \(H^1(K;\R)\) contains exactly one harmonic flow, so they form a space of dimension \(b_1\). For forms on a closed manifold, \(\Omega^k = d\,\Omega^{k-1}\oplus d^*\Omega^{k+1}\oplus\mathcal H^k\) with \(\dim\mathcal H^k = b_k\).</p>
			{@render go('big-picture/horizons')}
		</section>
	</div>

